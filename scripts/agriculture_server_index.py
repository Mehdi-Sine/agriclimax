"""Generate static server import paths so Next/Vercel can trace every agricultural artifact."""
import argparse
import json
from pathlib import Path


def generate() -> str:
    root = Path("apps/web/data/agriculture")
    lines = ["// Generated by scripts/agriculture_server_index.py; do not edit.", "import 'server-only';", "import type { AgriculturalDataset, AgriculturalManifest, WheatAgriculturalContext } from '../../features/agriculture/model';"]
    sources = []
    missing = []
    ids = []
    for source in ["saa", "rpg"]:
        manifest = root / f"{source}-manifest.json"
        if not manifest.exists():
            missing.append(f"{source}-manifest.json")
            continue
        lines.append(f"import {source} from '../../data/agriculture/{source}-manifest.json';")
        sources.append(source)
        ids.extend(i["id"] for i in json.loads(manifest.read_text())["indicators"])
    if len(ids) != len(set(ids)):
        raise ValueError("Duplicate agricultural indicator")
    lines += [f"export const sources = [{','.join(sources)}] as unknown as AgriculturalManifest[];", f"export const sourceErrors: string[] = {json.dumps(missing)};"]
    if (root / "rpg-wheat-context.json").exists():
        lines.append("export const loadWheatContext = async (): Promise<WheatAgriculturalContext | null> => (await import('../../data/agriculture/rpg-wheat-context.json')).default as unknown as WheatAgriculturalContext;")
    else:
        lines.append("export const loadWheatContext = async (): Promise<WheatAgriculturalContext | null> => null;")
    lines.append("export const datasets: Record<string, () => Promise<AgriculturalDataset>> = {")
    for identifier in sorted(ids):
        if not (root / f"{identifier}.json").is_file():
            raise ValueError(f"Missing qualified artifact: {identifier}")
        lines.append(f"  '{identifier}': async () => (await import('../../data/agriculture/{identifier}.json')).default as unknown as AgriculturalDataset,")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = Path("apps/web/lib/server/agriculture-index.ts")
    result = generate()
    if args.check:
        return int(not target.exists() or target.read_text() != result)
    target.write_text(result)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
